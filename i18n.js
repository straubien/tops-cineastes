// ── DATES ───────────────────────────────────────────────────────────────
// Les dates du site public suivaient toujours le format francais, meme en
// anglais. Ces trois fonctions lisent la langue choisie et laissent le
// navigateur ecrire la date comme il convient (actions A-076 a A-080).
//
// L'anglais utilise en-GB : jour d'abord et horloge 24 h, comme le francais.
// Seuls les noms de mois changent (« 30 sept. 2026 » -> « 30 Sept 2026 »).
// Les dates purement numeriques restent donc 30/09/2026 dans les deux
// langues : c'est voulu, et cela evite toute ambiguite avec le format
// americain 09/30/2026.
function tcLocale(){
  try{ return (localStorage.getItem('tc-lang') === 'en') ? 'en-GB' : 'fr-FR'; }
  catch(e){ return 'fr-FR'; }
}

function tcDate(iso, opts){
  if(!iso) return '';   // null, undefined ou chaine vide : pas de 01/01/1970
  try{
    var d = new Date(iso);
    if(isNaN(d.getTime())) return '';
    return d.toLocaleDateString(tcLocale(), opts);
  }catch(e){ return ''; }
}

// Date compacte (fil d'actualites, liste des soumissions).
// En francais : 30/09/2026. En anglais le mois est ecrit, car le format
// tout en chiffres est ambigu d'un pays a l'autre : « 03/01/2026 » se lit
// 3 janvier ici et January 3rd aux Etats-Unis. « 3 Jan 2026 » ne trompe
// personne (action A-080).
function tcDateCourte(iso){
  return (tcLocale() === 'fr-FR')
    ? tcDate(iso, { day:'2-digit', month:'2-digit', year:'numeric' })
    : tcDate(iso, { day:'numeric',  month:'short',  year:'numeric' });
}

function tcDateHeure(iso){
  if(!iso) return '';   // null, undefined ou chaine vide : pas de 01/01/1970
  try{
    var d = new Date(iso);
    if(isNaN(d.getTime())) return '';
    var loc = tcLocale();
    return d.toLocaleDateString(loc, { day:'numeric', month:'short', year:'numeric' })
         + t('date_liaison')
         + d.toLocaleTimeString(loc, { hour:'2-digit', minute:'2-digit' });
  }catch(e){ return ''; }
}

function t(key, arg){
  var lang='fr';
  try{ lang = localStorage.getItem('tc-lang') || 'fr'; }catch(e){}
  var dict = TC_TRANSLATIONS[lang] || TC_TRANSLATIONS.fr;
  var val = (dict[key] !== undefined) ? dict[key] : TC_TRANSLATIONS.fr[key];
  if(typeof val === 'function') return val(arg);
  return (val !== undefined) ? val : key;
}

function applyLang(lang){
  try{ localStorage.setItem('tc-lang', lang); }catch(e){}
  document.documentElement.setAttribute('lang', lang === 'en' ? 'en' : 'fr');
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var val = t(el.getAttribute('data-i18n'));
    if(val) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el){
    var val = t(el.getAttribute('data-i18n-ph'));
    if(val) el.placeholder = val;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el){
    var val = t(el.getAttribute('data-i18n-title'));
    if(val) el.title = val;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function(el){
    var val = t(el.getAttribute('data-i18n-aria'));
    if(val) el.setAttribute('aria-label', val);
  });
  document.querySelectorAll('.btn-lang').forEach(function(btn){
    var gifSrc = lang === 'fr' ? 'english.gif' : 'francais.gif';
    var gifAlt = lang === 'fr' ? 'EN' : 'FR';
    btn.innerHTML = '<img src="'+gifSrc+'" alt="'+gifAlt+'" class="btn-lang-img" style="display:block;opacity:0.7">';
    btn.title = lang === 'fr' ? 'Switch to English' : 'Passer en français';
  });
  if(typeof window.tcAfterLangChange === 'function') window.tcAfterLangChange();
}

function toggleLang(){
  var lang='fr';
  try{ lang = localStorage.getItem('tc-lang') || 'fr'; }catch(e){}
  applyLang(lang === 'fr' ? 'en' : 'fr');
}

// Appliquer au chargement si la langue n'est pas FR
(function(){
  var lang='fr';
  try{ lang = localStorage.getItem('tc-lang') || 'fr'; }catch(e){}
  if(lang === 'en'){
    if(document.readyState === 'loading'){
      document.addEventListener('DOMContentLoaded', function(){ applyLang('en'); });
    } else {
      applyLang('en');
    }
  }
})();
